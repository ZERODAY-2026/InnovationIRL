-- DataMind data-change demo: run as DATAMIND_ADMIN (the app's DATAMIND_READER role cannot write).
-- Adds one large 1995 order for a customer in JAPAN, tagged 'DATAMIND_DEMO' so demo_revert.sql removes exactly it.
-- Demo: ask "Which 5 nations had the highest revenue in 1995?", run this script, then press "Re-run on live data":
-- the same SQL returns a new answer under a new query ID, and the app lists what changed.
USE ROLE DATAMIND_ADMIN;
USE WAREHOUSE DATAMIND_WH;

INSERT INTO DATAMIND.TPCH.ORDERS
  (O_ORDERKEY, O_CUSTKEY, O_ORDERSTATUS, O_TOTALPRICE, O_ORDERDATE, O_ORDERPRIORITY, O_CLERK, O_SHIPPRIORITY, O_COMMENT)
SELECT 9000001, MIN(C_CUSTKEY), 'F', 60000000.00, '1995-06-15', '1-URGENT', 'Clerk#000000001', 0, 'DATAMIND_DEMO'
FROM DATAMIND.TPCH.CUSTOMER JOIN DATAMIND.TPCH.NATION ON C_NATIONKEY = N_NATIONKEY
WHERE N_NAME = 'JAPAN';

-- Part 1 is supplied by supplier 2 in TPC-H SF1 (a valid PARTSUPP pair).
INSERT INTO DATAMIND.TPCH.LINEITEM
  (L_ORDERKEY, L_PARTKEY, L_SUPPKEY, L_LINENUMBER, L_QUANTITY, L_EXTENDEDPRICE, L_DISCOUNT, L_TAX, L_RETURNFLAG,
   L_LINESTATUS, L_SHIPDATE, L_COMMITDATE, L_RECEIPTDATE, L_SHIPINSTRUCT, L_SHIPMODE, L_COMMENT)
VALUES
  (9000001, 1, 2, 1, 50, 60000000.00, 0.00, 0.00, 'N', 'F', '1995-06-20', '1995-07-01', '1995-06-25',
   'NONE', 'AIR', 'DATAMIND_DEMO');

-- Check: one demo order and one demo line.
SELECT (SELECT COUNT(*) FROM DATAMIND.TPCH.ORDERS WHERE O_COMMENT = 'DATAMIND_DEMO') AS DEMO_ORDERS,
       (SELECT COUNT(*) FROM DATAMIND.TPCH.LINEITEM WHERE L_COMMENT = 'DATAMIND_DEMO') AS DEMO_LINES;
