-- DataMind Snowflake setup. Run once as ACCOUNTADMIN in a Snowsight worksheet ("Run all").
-- Idempotent: safe to re-run after partial manual setup.
-- Creates: an XS warehouse with a daily credit cap, roles, the DATAMIND database (TPCH and OWID schemas),
-- full copies of the 8 TPC-H SF1 tables (inside this account only), grants, and the app's key-pair service user.

USE ROLE ACCOUNTADMIN;

-- 1. Compute: extra-small, suspends after 60 s idle, capped at 10 credits per day.
CREATE WAREHOUSE IF NOT EXISTS DATAMIND_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 120
  COMMENT = 'DataMind: XS, auto-suspend 60 s';
CREATE RESOURCE MONITOR IF NOT EXISTS DATAMIND_RM
  WITH CREDIT_QUOTA = 10 FREQUENCY = DAILY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 90 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE DATAMIND_WH SET RESOURCE_MONITOR = DATAMIND_RM;

-- 2. Roles: DATAMIND_READER is the app (SELECT only); DATAMIND_ADMIN loads data and runs the data-change demo.
CREATE ROLE IF NOT EXISTS DATAMIND_READER COMMENT = 'DataMind app: read-only on DATAMIND schemas';
CREATE ROLE IF NOT EXISTS DATAMIND_ADMIN COMMENT = 'DataMind: data loads and the data-change demo';
GRANT ROLE DATAMIND_READER TO ROLE DATAMIND_ADMIN;
GRANT ROLE DATAMIND_ADMIN TO ROLE SYSADMIN;
SET MY_USER = CURRENT_USER();
GRANT ROLE DATAMIND_ADMIN TO USER IDENTIFIER($MY_USER);

-- 3. Data. TPC-H sample data has no open licence: it is copied inside this account only and never exported.
--    If SNOWFLAKE_SAMPLE_DATA is missing in your account, first run:
--    CREATE DATABASE SNOWFLAKE_SAMPLE_DATA FROM SHARE SFC_SAMPLES.SAMPLE_DATA;
CREATE DATABASE IF NOT EXISTS DATAMIND COMMENT = 'DataMind datasets';
CREATE SCHEMA IF NOT EXISTS DATAMIND.TPCH;
CREATE SCHEMA IF NOT EXISTS DATAMIND.OWID;
USE WAREHOUSE DATAMIND_WH;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.REGION   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.NATION   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.SUPPLIER AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.CUSTOMER AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.PART     AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.PARTSUPP AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PARTSUPP;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.ORDERS   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;
CREATE TABLE IF NOT EXISTS DATAMIND.TPCH.LINEITEM AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;

-- 4. Grants. The reader gets usage and SELECT on the DATAMIND schemas and nothing else.
GRANT USAGE ON WAREHOUSE DATAMIND_WH TO ROLE DATAMIND_READER;
GRANT USAGE, OPERATE ON WAREHOUSE DATAMIND_WH TO ROLE DATAMIND_ADMIN;
GRANT USAGE ON DATABASE DATAMIND TO ROLE DATAMIND_READER;
GRANT USAGE ON SCHEMA DATAMIND.TPCH TO ROLE DATAMIND_READER;
GRANT USAGE ON SCHEMA DATAMIND.OWID TO ROLE DATAMIND_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND.TPCH TO ROLE DATAMIND_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAMIND.TPCH TO ROLE DATAMIND_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND.OWID TO ROLE DATAMIND_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAMIND.OWID TO ROLE DATAMIND_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA DATAMIND.OWID TO ROLE DATAMIND_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA DATAMIND.OWID TO ROLE DATAMIND_READER;
-- Admin: writes for the data-change demo (TPCH) and the OWID seed.
GRANT INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA DATAMIND.TPCH TO ROLE DATAMIND_ADMIN;
GRANT INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA DATAMIND.TPCH TO ROLE DATAMIND_ADMIN;
GRANT CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA DATAMIND.OWID TO ROLE DATAMIND_ADMIN;

-- 5. Every role inherits PUBLIC, and new accounts grant the sample database to PUBLIC. To keep the app role
--    on DATAMIND only, move that access to SYSADMIN. Account-wide change: other roles lose the sample database.
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE SYSADMIN;
REVOKE IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA FROM ROLE PUBLIC;

-- 6. The app's service user: key-pair only (service users cannot use passwords), read-only role.
CREATE USER IF NOT EXISTS DATAMIND_APP
  TYPE = SERVICE
  DEFAULT_ROLE = DATAMIND_READER
  DEFAULT_WAREHOUSE = DATAMIND_WH
  DEFAULT_NAMESPACE = DATAMIND.TPCH
  COMMENT = 'DataMind app: key-pair auth, read-only';
GRANT ROLE DATAMIND_READER TO USER DATAMIND_APP;
ALTER USER DATAMIND_APP SET STATEMENT_TIMEOUT_IN_SECONDS = 60;
-- Register each laptop's public key: run `python scripts/gen_keypair.py` and paste the ALTER USER line it
-- prints (slot 1 = RSA_PUBLIC_KEY, slot 2 = RSA_PUBLIC_KEY_2). For a third laptop, create DATAMIND_APP_3
-- with the block above and run gen_keypair.py with --user DATAMIND_APP_3.

-- 7. Checks: 8 tables with rows, and the reader's grants.
SELECT TABLE_NAME, ROW_COUNT FROM DATAMIND.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'TPCH' ORDER BY TABLE_NAME;
SHOW GRANTS TO ROLE DATAMIND_READER;
