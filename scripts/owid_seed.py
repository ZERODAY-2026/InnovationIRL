"""Build the OWID CO2/energy subset and the SQL that seeds DATAMIND.OWID.CO2.

Source: Our World in Data, CO2 and Greenhouse Gas Emissions dataset (https://github.com/owid/co2-data), CC BY 4.0.
Steps:
  python scripts/owid_seed.py --download   # fetch the full CSV into data/raw/owid/ (git-ignored)
  python scripts/owid_seed.py              # write data/owid/owid_co2_subset.csv and snowflake/owid_seed.generated.sql
Then run snowflake/owid_seed.generated.sql in Snowsight as DATAMIND_ADMIN (the app's role is read-only).
Missing values stay NULL on purpose: they are real gaps in the source data.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_URL = "https://raw.githubusercontent.com/owid/co2-data/master/owid-co2-data.csv"
RAW = ROOT / "data" / "raw" / "owid" / "owid-co2-data.csv"
SUBSET = ROOT / "data" / "owid" / "owid_co2_subset.csv"
SEED_SQL = ROOT / "snowflake" / "owid_seed.generated.sql"
FIRST_YEAR = 2000
# source column -> (Snowflake column, Snowflake type)
COLUMNS = {
    "country": ("COUNTRY", "VARCHAR"),
    "year": ("YEAR", "NUMBER(4,0)"),
    "iso_code": ("ISO_CODE", "VARCHAR"),
    "population": ("POPULATION", "NUMBER(38,0)"),
    "gdp": ("GDP", "NUMBER(38,2)"),
    "co2": ("CO2", "NUMBER(38,3)"),
    "co2_per_capita": ("CO2_PER_CAPITA", "NUMBER(38,3)"),
    "share_global_co2": ("SHARE_GLOBAL_CO2", "NUMBER(38,3)"),
    "coal_co2": ("COAL_CO2", "NUMBER(38,3)"),
    "oil_co2": ("OIL_CO2", "NUMBER(38,3)"),
    "gas_co2": ("GAS_CO2", "NUMBER(38,3)"),
    "primary_energy_consumption": ("PRIMARY_ENERGY_CONSUMPTION", "NUMBER(38,3)"),
    "energy_per_capita": ("ENERGY_PER_CAPITA", "NUMBER(38,3)"),
}
BATCH = 500


def download() -> None:
    import httpx

    RAW.parent.mkdir(parents=True, exist_ok=True)
    response = httpx.get(SOURCE_URL, timeout=120, follow_redirects=True)
    response.raise_for_status()
    RAW.write_bytes(response.content)
    print(f"downloaded {len(response.content):,} bytes to {RAW.relative_to(ROOT).as_posix()}")


def build_subset() -> list[list[str]]:
    with RAW.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        missing = [c for c in COLUMNS if c not in (reader.fieldnames or [])]
        if missing:
            raise SystemExit(f"source CSV lacks columns {missing}; the OWID schema may have changed")
        rows = [[row[c].strip() for c in COLUMNS] for row in reader if row["year"] and int(row["year"]) >= FIRST_YEAR]
    SUBSET.parent.mkdir(parents=True, exist_ok=True)
    with SUBSET.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow([name for name, _ in COLUMNS.values()])
        writer.writerows(rows)
    return rows


def _sql_value(raw: str, sql_type: str) -> str:
    if raw == "":
        return "NULL"
    if sql_type == "VARCHAR":
        return "'" + raw.replace("'", "''") + "'"
    float(raw)  # rejects anything that is not a number
    return raw


def write_seed_sql(rows: list[list[str]]) -> None:
    names = [name for name, _ in COLUMNS.values()]
    types = [sql_type for _, sql_type in COLUMNS.values()]
    lines = [
        "-- GENERATED by scripts/owid_seed.py from Our World in Data CO2 data (CC BY 4.0). Run as DATAMIND_ADMIN.",
        "USE ROLE DATAMIND_ADMIN;",
        "USE WAREHOUSE DATAMIND_WH;",
        "CREATE OR REPLACE TABLE DATAMIND.OWID.CO2 (" + ", ".join(f"{n} {t}" for n, t in zip(names, types)) + ");",
    ]
    for start in range(0, len(rows), BATCH):
        values = ",\n".join("(" + ", ".join(_sql_value(v, t) for v, t in zip(row, types)) + ")"
                            for row in rows[start:start + BATCH])
        lines.append(f"INSERT INTO DATAMIND.OWID.CO2 ({', '.join(names)}) VALUES\n{values};")
    lines.append("SELECT COUNT(*) AS ROWS_LOADED, COUNT(DISTINCT COUNTRY) AS ENTITIES, MIN(YEAR) AS FIRST_YEAR, "
                 "MAX(YEAR) AS LAST_YEAR FROM DATAMIND.OWID.CO2;")
    SEED_SQL.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true", help="fetch the full source CSV first (network)")
    args = parser.parse_args()
    if args.download:
        download()
    if not RAW.exists():
        print("source CSV missing: run with --download first", file=sys.stderr)
        return 1
    rows = build_subset()
    write_seed_sql(rows)
    empty = sum(1 for row in rows for v in row if v == "")
    print(f"subset: {len(rows):,} rows x {len(COLUMNS)} columns ({empty:,} empty cells kept as NULL) -> "
          f"{SUBSET.relative_to(ROOT).as_posix()}; seed SQL -> {SEED_SQL.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
